const missed = (towns: Town[]) => towns.filter(([, region, lat, lng]) => !regionsNear({ lat, lng }).some((r) => r.name === region)).map(([name]) => name);

describe('받을 시도 고르기(가장 가까운 앵커 + 여유 거리 안의 모든 시도, 최대 3곳)', () => {
  it('앵커로 조정한 시군청 표에서 실제 시도가 모두 선택 목록에 들어 있다', () => {
    expect(TUNED).toHaveLength(97);
    expect(missed(TUNED)).toEqual([]);
  });

  it('조정에 쓰지 않은 두 번째 표에서도 실제 시도가 모두 들어 있다', () => {
    expect(HELD_OUT.length).toBeGreaterThan(70);
    expect(missed(HELD_OUT)).toEqual([]);
  });

  it('표의 모든 지점이 남한 영토 안이다(독도·울릉·백령·연평·마라도·강원 휴전선 쪽 군 포함)', () => {
    expect([...TUNED, ...HELD_OUT].filter(([, , lat, lng]) => !inSouthKorea({ lat, lng })).map(([name]) => name)).toEqual([]);
  });

  it('대표 사례: 이전 방식(가장 가까운 시도 + 경계 근처 한 곳)이 놓치던 지점', () => {
    const names = (lat: number, lng: number) => regionsNear({ lat, lng }).map((r) => r.name);
    expect(names(37.5034, 126.766)).toContain('경기'); // 부천: 인천이 가장 가깝다
    expect(names(37.38, 126.803)).toContain('경기'); // 시흥
    expect(names(37.4786, 126.8646)).toContain('경기'); // 광명: 서울·인천이 가깝다
    expect(names(35.8251, 128.7414)).toContain('경북'); // 경산: 대구가 가깝다
    expect(names(36.1087, 127.4881)).toContain('충남'); // 금산: 전북·대전이 가깝다
    expect(names(36.3064, 127.5713)).toContain('충북'); // 옥천: 대전이 가깝다
    expect(names(35.6867, 127.9095)).toContain('경남'); // 거창: 전북이 가깝다
    expect(names(34.8377, 127.8924)).toContain('경남'); // 남해: 전남이 가깝다
    expect(names(35.282, 127.292)).toContain('광주·전남'); // 곡성: 전북이 가깝다
    expect(names(38.1466, 127.3132)).toContain('강원'); // 철원: 경기가 가깝다
  });

  it('가장 가까운 시도가 맨 앞이고, 여유 거리 안의 시도는 가까운 순으로 최대 3곳이다', () => {
    const seoul = regionsNear({ lat: 37.5665, lng: 126.978 }).map((r) => r.name);
    expect(seoul[0]).toBe('서울');
    expect(seoul.length).toBeLessThanOrEqual(EV_REGIONS_MAX_PER_QUERY);
    expect(regionsNear({ lat: 37.5, lng: 126.65 }).map((r) => r.name)).toEqual(['인천', '경기', '서울']);
    expect(regionsNear({ lat: 33.4996, lng: 126.5312 }).map((r) => r.name)).toEqual(['제주']); // 제주는 육지와 멀어 한 곳
    expect(regionsNear({ lat: 37.5665, lng: 126.978 }, 0, 5).map((r) => r.name)).toEqual(['서울']); // 여유 0이면 가장 가까운 곳뿐
    expect(regionsNear({ lat: 37.5, lng: 126.65 }, EV_REGION_MARGIN_METERS, 2).map((r) => r.name)).toEqual(['인천', '경기']); // 최대 곳 수
  });

  it('시도 앵커는 전부 남한 영토 안이다', () => {
    expect(REGIONS.flatMap((r) => r.anchors).filter((a) => !inSouthKorea(a))).toEqual([]);
  });
});

